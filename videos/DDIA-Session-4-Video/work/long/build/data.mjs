// Seeded datasets shared by the narration (numbers spoken aloud) and the visuals (charts drawn from the same arrays).
// Run: node build/data.mjs → data/datasets.json, stage/datasets.js (window.DATA), data/numbers.md (the ONLY illustrative
// numbers the script may quote). Re-run whenever you change a seed or a parameter, then re-check the script.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");

function mulberry32(seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// ---- A tiny payments fact table: 12 rows × 6 columns (simplified illustration).
// The country column is the deck's sequence, so the table, the bitmaps and the lab all agree.
const rng = mulberry32(20170316);
const columns = ["id", "date", "merchant", "country", "method", "amount"];
const country = ["DE", "DE", "DE", "FR", "FR", "NL", "NL", "NL", "NL", "DE", "DE", "FR"];
const merchants = ["Acme", "Bolt", "Cora"];
const methods = ["card", "wallet", "bank"];
const dates = ["Jun 3", "Jun 1", "Jun 2", "Jun 1", "Jun 3", "Jun 2", "Jun 1", "Jun 3", "Jun 2", "Jun 1", "Jun 2", "Jun 3"];
const rows = country.map((c, i) => [
  i + 1,
  dates[i],
  merchants[Math.floor(rng() * 3)],
  c,
  methods[rng() < 0.55 ? 0 : rng() < 0.6 ? 1 : 2],
  5 * Math.round((10 + rng() * 190) / 5),
]);
const R = rows.length, C = columns.length;
const sumDE = rows.filter((r) => r[3] === "DE").reduce((s, r) => s + r[5], 0);
const lab = {
  scan: { sql: "SELECT SUM(amount) WHERE country = 'DE'", rowStoreCells: R * C, columnStoreCells: 2 * R, pct: Math.round((200 * R) / (R * C)), result: sumDE },
  lookup: { sql: "SELECT * WHERE id = 4", rowStoreCells: C, rowStorePlaces: 1, columnStoreCells: C, columnStorePlaces: C },
};
// Scaled up: a 100-column fact table and a query that needs 4 of them.
const wide = { columns: 100, used: 4, pct: 4 };

// ---- Bitmaps and run-length encoding (zeros first, as in the book).
const bitmap = (v) => country.map((c) => (c === v ? 1 : 0));
const runs = (bits) => {
  const out = []; let cur = 0, n = 0;
  for (const b of bits) { if (b === cur) n++; else { out.push(n); cur = b; n = 1; } }
  out.push(n); return out;
};
const bitmaps = Object.fromEntries(["DE", "FR", "NL"].map((v) => [v, { bits: bitmap(v).join(""), runs: runs(bitmap(v)) }]));
const orBits = bitmap("DE").map((b, i) => b | bitmap("NL")[i]).join("");
const cardBits = rows.map((r) => (r[4] === "card" ? 1 : 0)).join("");
const andBits = bitmap("DE").map((b, i) => b & +cardBits[i]).join("");

// ---- Sort order: the same 12 rows sorted by date, then merchant.
const sorted = [...rows].sort((a, b) => (a[1] < b[1] ? -1 : a[1] > b[1] ? 1 : a[2] < b[2] ? -1 : a[2] > b[2] ? 1 : a[0] - b[0]));
const countRuns = (vals) => vals.reduce((n, v, i) => n + (i === 0 || v !== vals[i - 1] ? 1 : 0), 0);
const sortDemo = {
  order: sorted.map((r) => r[0]),
  dateRunsBefore: countRuns(rows.map((r) => r[1])), dateRunsAfter: countRuns(sorted.map((r) => r[1])),
  merchantRunsAfter: countRuns(sorted.map((r) => r[2])), amountRunsAfter: countRuns(sorted.map((r) => r[5])),
};

// ---- Data cube: SUM(amount) in thousands of dollars by date × merchant (illustrative).
const rngC = mulberry32(31);
const cubeDates = ["Jun 1", "Jun 2", "Jun 3", "Jun 4"];
const cells = cubeDates.map(() => merchants.map(() => Math.round(20 + rngC() * 70)));
const rowTotals = cells.map((r) => r.reduce((a, b) => a + b, 0));
const colTotals = merchants.map((_, j) => cells.reduce((s, r) => s + r[j], 0));
const grand = rowTotals.reduce((a, b) => a + b, 0);
const cube = { dates: cubeDates, merchants, cells, rowTotals, colTotals, grand };

const DATA = { columns, rows, lab, wide, bitmaps, orBits, cardBits, andBits, sorted, sortDemo, cube };
fs.mkdirSync(path.join(root, "data"), { recursive: true });
fs.writeFileSync(path.join(root, "data/datasets.json"), JSON.stringify(DATA));
fs.writeFileSync(path.join(root, "stage/datasets.js"), "window.DATA = " + JSON.stringify(DATA) + ";\n");

const tbl = (hdr, rs) => `| ${hdr.join(" | ")} |\n|${hdr.map(() => "---").join("|")}|\n` + rs.map((r) => `| ${r.join(" | ")} |`).join("\n");
const md = `# Numbers the narration may quote (generated by build/data.mjs — do not edit by hand)

All of these are a simplified illustration (seeded, invented payments). Label them on screen.

## Payments fact table (12 rows × 6 columns)
${tbl(columns, rows)}

## Column-store lab
- \`${lab.scan.sql}\`: row store reads ${lab.scan.rowStoreCells} cells (every column of every row); column store reads ${lab.scan.columnStoreCells} cells (2 columns × ${R} rows) = ${lab.scan.pct}% of the table. Result: ${lab.scan.result}.
- \`${lab.lookup.sql}\`: both read ${C} cells; the row store finds them in ${lab.lookup.rowStorePlaces} place, the column store in ${lab.lookup.columnStorePlaces} files.
- Scaled up: a ${wide.columns}-column fact table, a query that uses ${wide.used} columns → it needs about ${wide.pct}% of the data (before compression).

## Bitmaps (country column: ${country.join(" ")})
${Object.entries(bitmaps).map(([v, b]) => `- ${v}: ${b.bits} → runs ${b.runs.join(", ")} (zeros first)`).join("\n")}
- country IN ('DE','NL') = DE OR NL = ${orBits}
- method = card: ${cardBits}; country = 'DE' AND method = 'card' = ${andBits} (${[...andBits].filter((b) => b === "1").length === 1 ? "one row" : [...andBits].filter((b) => b === "1").length + " rows"})

## Sort by date, then merchant
- Row order after sorting (ids): ${sortDemo.order.join(", ")}
- date column: ${sortDemo.dateRunsBefore} runs before sorting → ${sortDemo.dateRunsAfter} runs after; merchant: ${sortDemo.merchantRunsAfter} runs; amount: ${sortDemo.amountRunsAfter} runs (jumbled).

## Data cube: SUM(amount), thousands of dollars, date × merchant
${tbl(["date", ...merchants, "total"], cubeDates.map((d, i) => [d, ...cells[i], rowTotals[i]]).concat([["total", ...colTotals, grand]]))}
`;
fs.writeFileSync(path.join(root, "data/numbers.md"), md);
console.log(md);
