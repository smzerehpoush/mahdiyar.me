// Generates the seeded datasets used by both the narration (numbers spoken aloud) and the visuals.
// Run: node build/data.mjs  → data/datasets.json + data/numbers.md
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");

function mulberry32(seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function gaussFactory(rng) {
  return () => {
    let u = 0, v = 0;
    while (!u) u = rng();
    while (!v) v = rng();
    return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
  };
}
// Nearest-rank percentile.
const pct = (sorted, p) => sorted[Math.max(0, Math.ceil((p / 100) * sorted.length) - 1)];
const mean = (a) => a.reduce((s, x) => s + x, 0) / a.length;
const stats = (a) => {
  const s = [...a].sort((x, y) => x - y);
  return { n: a.length, mean: Math.round(mean(a)), p50: pct(s, 50), p95: pct(s, 95), p99: pct(s, 99), max: s[s.length - 1] };
};

// --- Percentile demo: 1,000 requests, log-normal around ~110 ms; then 2% become long pauses (0.8–2.0 s).
const rng = mulberry32(20121130);
const g = gaussFactory(rng);
const normal = Array.from({ length: 1000 }, () => Math.round(110 * Math.exp(0.33 * g())));
const withPauses = [...normal];
const pauseIdx = new Set();
while (pauseIdx.size < 20) pauseIdx.add(Math.floor(rng() * 1000));
for (const i of pauseIdx) withPauses[i] = 800 + Math.round(rng() * 1200);

// --- Aggregation demo: three servers with different traffic volumes and tails.
const rngB = mulberry32(99);
const gB = gaussFactory(rngB);
const serverA = Array.from({ length: 6000 }, () => Math.round(80 * Math.exp(0.28 * gB())));
const serverB = Array.from({ length: 3000 }, () => Math.round(95 * Math.exp(0.3 * gB())));
const serverC = Array.from({ length: 1000 }, () =>
  rngB() < 0.06 ? 700 + Math.round(rngB() * 900) : Math.round(120 * Math.exp(0.3 * gB()))
);
const combined = [...serverA, ...serverB, ...serverC];
const sA = stats(serverA), sB = stats(serverB), sC = stats(serverC), sAll = stats(combined);
const avgOfP99 = Math.round((sA.p99 + sB.p99 + sC.p99) / 3);

// --- Fixed facts (circa 2012 Twitter figures, disk illustration, tail amplification).
const disk = { disks: 10000, mttfYears: 30, perDay: +(10000 / (30 * 365)).toFixed(2) };
const amp = { calls: 100, pSlow: 0.01, pAnySlow: +(1 - Math.pow(0.99, 100)).toFixed(3) };
const twitter = { tweetsPerSec: 4600, peakTweetsPerSec: 12000, timelineReadsPerSec: 300000, avgFollowers: 75,
  insertionsPerSec: 4600 * 75, readsPerTweet: Math.round(300000 / 4600), celebrityFollowers: 30000000 };

const out = {
  percentiles: { normal, withPauses, pauseIdx: [...pauseIdx].sort((a, b) => a - b), before: stats(normal), after: stats(withPauses) },
  aggregate: { servers: [
      { name: "Server A", values: serverA, ...sA },
      { name: "Server B", values: serverB, ...sB },
      { name: "Server C", values: serverC, ...sC },
    ], combined: sAll, avgOfP99 },
  disk, amp, twitter,
};
// Strip large arrays of per-server values into histograms (10 ms bins up to 2 s) to keep the stage payload small.
const hist = (vals, bin = 10, max = 2000) => {
  const h = new Array(Math.ceil(max / bin)).fill(0);
  for (const v of vals) h[Math.min(h.length - 1, Math.floor(v / bin))]++;
  return h;
};
for (const s of out.aggregate.servers) { s.hist = hist(s.values); delete s.values; }
out.aggregate.combinedHist = hist(combined);

fs.mkdirSync(path.join(root, "data"), { recursive: true });
fs.writeFileSync(path.join(root, "data/datasets.json"), JSON.stringify(out));
fs.writeFileSync(path.join(root, "stage/datasets.js"), "window.DATA = " + JSON.stringify(out) + ";\n");

const b = out.percentiles.before, a = out.percentiles.after;
const md = `# Numbers the narration may quote (generated by build/data.mjs — do not edit by hand)

## Percentile demo (1,000 simulated requests; illustrative)
| | mean | p50 | p95 | p99 | max |
|---|---|---|---|---|---|
| normal traffic | ${b.mean} ms | ${b.p50} ms | ${b.p95} ms | ${b.p99} ms | ${b.max} ms |
| + 20 long pauses (2%, 0.8–2.0 s) | ${a.mean} ms | ${a.p50} ms | ${a.p95} ms | ${a.p99} ms | ${a.max} ms |

## Aggregation demo (illustrative)
| | requests | p50 | p99 |
|---|---|---|---|
| Server A | ${sA.n} | ${sA.p50} ms | ${sA.p99} ms |
| Server B | ${sB.n} | ${sB.p50} ms | ${sB.p99} ms |
| Server C | ${sC.n} | ${sC.p50} ms | ${sC.p99} ms |
| **Average of the three p99s (wrong)** | | | **${avgOfP99} ms** |
| **p99 of combined histogram (right)** | ${sAll.n} | ${sAll.p50} ms | **${sAll.p99} ms** |

## Fixed figures
- Disks: ${disk.disks} disks, assumed MTTF ${disk.mttfYears} years → ${disk.perDay} failures/day ≈ about one per day.
- Tail amplification: 1 − 0.99^100 = ${amp.pAnySlow} → about 63%.
- Twitter, circa 2012: ${twitter.tweetsPerSec} tweets/s avg (> ${twitter.peakTweetsPerSec} peak), ${twitter.timelineReadsPerSec} timeline reads/s,
  avg ${twitter.avgFollowers} followers → ${twitter.insertionsPerSec} insertions/s; ≈ ${twitter.readsPerTweet} reads per tweet; celebrity ${twitter.celebrityFollowers} followers.
`;
fs.writeFileSync(path.join(root, "data/numbers.md"), md);
console.log(md);
