// Seeded datasets shared by the narration (numbers spoken aloud) and the visuals (charts drawn from the same arrays).
// Copy of the skill's reference/data-template.mjs — replace the example dataset with the chapter's own.
// Run: node build/data.mjs → data/datasets.json, stage/datasets.js (window.DATA), data/numbers.md (the ONLY illustrative
// numbers the script may quote). Re-run whenever you change a seed or a parameter, then re-check the script.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");

function mulberry32(seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const gaussFactory = (rng) => () => { let u = 0, v = 0; while (!u) u = rng(); while (!v) v = rng(); return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v); };
const pct = (sorted, p) => sorted[Math.max(0, Math.ceil((p / 100) * sorted.length) - 1)]; // nearest-rank percentile

// ---- Example dataset (replace): 1,000 simulated request durations, log-normal around ~110 ms.
const rng = mulberry32(42), g = gaussFactory(rng);
const requests = Array.from({ length: 1000 }, () => Math.round(Math.exp(Math.log(110) + 0.3 * g())));
const s = [...requests].sort((a, b) => a - b);
const stats = { p50: pct(s, 50), p99: pct(s, 99), mean: Math.round(s.reduce((a, b) => a + b, 0) / s.length) };

const DATA = { example: { requests, stats } };
fs.mkdirSync(path.join(root, "data"), { recursive: true });
fs.writeFileSync(path.join(root, "data/datasets.json"), JSON.stringify(DATA));
fs.writeFileSync(path.join(root, "stage/datasets.js"), "window.DATA = " + JSON.stringify(DATA) + ";\n");
const md = `# Numbers the narration may quote (generated by build/data.mjs — do not edit by hand)

## Example (illustrative, simulated)
- 1,000 requests: mean ${stats.mean} ms, p50 ${stats.p50} ms, p99 ${stats.p99} ms.
`;
fs.writeFileSync(path.join(root, "data/numbers.md"), md);
console.log(md);
